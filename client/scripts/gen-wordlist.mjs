// Generates src/bip39-english.ts from the canonical @scure/bip39 English wordlist.
// Run once (npm run gen:wordlist). The wordlist is public-domain (BIP-39); embedding
// it keeps the client's *runtime* dependency set to exactly the four pinned crypto
// libraries (@scure/bip39 stays a devDependency used only for this generation step).
import { wordlist } from '@scure/bip39/wordlists/english.js';
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

if (wordlist.length !== 2048) {
  throw new Error(`expected 2048 words, got ${wordlist.length}`);
}
const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, '..', 'src', 'bip39-english.ts');

const body = wordlist.map((w) => `  '${w}',`).join('\n');
const contents = `// GENERATED by scripts/gen-wordlist.mjs from @scure/bip39 English wordlist (BIP-39, public domain).
// Do not edit by hand. Regenerate with: npm run gen:wordlist
export const BIP39_ENGLISH: readonly string[] = [
${body}
];

if (BIP39_ENGLISH.length !== 2048) {
  throw new Error('BIP39_ENGLISH must contain exactly 2048 words');
}
`;
writeFileSync(out, contents);
console.log(`wrote ${out} with ${wordlist.length} words`);
